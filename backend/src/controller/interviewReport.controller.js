const { extractTextFromPDF } = require("../services/pdf.service");
const interviewReportModel = require("../models/InterviewReport.model");
const generateInterviewReport = require("../services/ai.service");

// Helper to reliably get fields from form-data even with trailing spaces or case differences
function getFormField(body, fieldName) {
    if (!body || typeof body !== "object") return "";
    const cleanTarget = fieldName.toLowerCase().replace(/[^a-z0-9]/g, "");

    // 1. Direct match
    if (body[fieldName] !== undefined && body[fieldName] !== null) {
        return body[fieldName];
    }

    // 2. Fuzzy match across all keys (handles trailing spaces like "selfDescription ")
    for (const key of Object.keys(body)) {
        const cleanKey = key.trim().toLowerCase().replace(/[^a-z0-9]/g, "");
        if (cleanKey === cleanTarget) {
            return body[key];
        }
    }
    return "";
}

/**
 * @route POST /api/interview/generate
 * @description Extract resume text from uploaded PDF and receive jobDescription and selfDescription
 * @access public / private
 */
async function generateReportController(req, res) {
    try {
        if (!req.file) {
            return res.status(400).json({
                message: "Please upload a PDF resume"
            });
        }

        const resumeText = await extractTextFromPDF(req.file.buffer);

        if (!resumeText || !resumeText.trim()) {
            return res.status(422).json({
                message: "Could not extract text from this PDF resume"
            });
        }

        const selfDescription = getFormField(
            req.body,
            "selfDescription"
        );

        const jobDescription = getFormField(
            req.body,
            "jobDescription"
        );

        if (!selfDescription || !selfDescription.trim()) {
            return res.status(400).json({
                message: "Self description is required"
            });
        }

        if (!jobDescription || !jobDescription.trim()) {
            return res.status(400).json({
                message: "Job description is required"
            });
        }

        console.log("Starting AI interview report generation...");

        const reportData = await generateInterviewReport({
            resume: resumeText,
            selfDescription,
            jobDescription
        });

        console.log("AI interview report generated successfully.");

        const savedReport = await interviewReportModel.create({
            user: req.user?.id || null,
            resume: resumeText,
            selfDescription,
            jobDescription,
            matchScore: reportData.matchScore,
            technicalQuestions: reportData.technicalQuestions,
            behavioralQuestions: reportData.behavioralQuestions,
            skillGaps: reportData.skillGaps,
            preparationPlan: reportData.preparationPlan
        });

        console.log("Interview report saved to MongoDB.");

        return res.status(201).json({
            message: "Interview report generated successfully",
            report: savedReport
        });

    } catch (error) {
        console.error("Report Generation Error:", error);

        return res.status(500).json({
            message: "Failed to generate interview report",
            error: error.message
        });
    }
}
/**
 * @route GET /api/interview/:id
 * @description Fetch a specific interview report by ID
 * @access public / private
 */
async function getReportByIdController(req, res) {
    try {
        const { id } = req.params;
        const report = await interviewReportModel.findById(id);

        if (!report) {
            return res.status(404).json({
                message: "Interview report not found"
            });
        }

        return res.status(200).json({
            message: "Report fetched successfully",
            report
        });
    } catch (error) {
        console.error("Get Report Error:", error);
        return res.status(500).json({
            message: "Failed to fetch interview report",
            error: error.message
        });
    }
}

/**
 * @route GET /api/interview/user/all
 * @description Fetch all reports generated by the logged in user
 * @access private
 */
async function getUserReportsController(req, res) {
    try {
        if (!req.user?.id) {
            return res.status(401).json({
                message: "Unauthorized. Please log in."
            });
        }

        const reports = await interviewReportModel
            .find({ user: req.user.id })
            .sort({ createdAt: -1 });

        return res.status(200).json({
            message: "User reports fetched successfully",
            reports
        });
    } catch (error) {
        console.error("Get User Reports Error:", error);
        return res.status(500).json({
            message: "Failed to fetch user reports",
            error: error.message
        });
    }
}

module.exports = {
    generateReportController,
    getReportByIdController,
    getUserReportsController
};
